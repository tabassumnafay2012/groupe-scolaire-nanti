-- À coller dans Supabase > SQL Editor > New query > Run
create table if not exists public.candidates (
  id bigint generated by default as identity primary key,
  name text not null,
  class_name text not null,
  program text not null default '',
  photo_url text,
  created_at timestamptz not null default now()
);
create table if not exists public.votes (
  id bigint generated by default as identity primary key,
  candidate_id bigint not null references public.candidates(id) on delete cascade,
  created_at timestamptz not null default now()
);
-- Les fonctions Netlify utilisent la clé service_role côté serveur.
-- Ne jamais mettre SUPABASE_SERVICE_ROLE_KEY dans le HTML.
alter table public.candidates enable row level security;
alter table public.votes enable row level security;
-- Pas de politique publique : les accès passent par les fonctions serveur Netlify.
